-- Попытка входа по коду из письма помнит клиента и его регистрацию, под
-- которой начата (в том числе отложенная привязка Google: она хранится в той
-- же попытке). Проверка кода и повторная отправка сверяют их с текущей
-- регистрацией: клиент, удалённый и созданный заново с тем же id, — другое
-- приложение, и начатый у прежнего вход ему не переходит.
--
-- Попытки, начатые до обновления, клиента не знают: восстановить его нельзя,
-- поэтому они отклоняются, как попытка другой регистрации. Попытка живёт не
-- больше 15 минут, и пользователь, вводивший код во время обновления, просто
-- начинает вход заново.
alter table email_login_challenges add column client_id text;
alter table email_login_challenges add column client_registration_id uuid;
