-- Код авторизации, выданный по SSO-сессии (тихий вход, экран согласия),
-- помнит цепочку SSO браузера: обмен сверяет, что браузер не сменил в ней
-- аккаунт. Раньше цепочку искали по auth.loginId, а у SSO-сессий, начатых до
-- миграции 0013, его нет — их коды проверку цепочки обходили.
--
-- Коды, выданные до обновления, цепочку не знают и проверяются как раньше.
-- Код живёт 60 секунд, поэтому для пользователей обновление незаметно: ни
-- SSO-сессии, ни сессии приложений не обрываются.
alter table authorization_codes add column sso_chain_id uuid;
