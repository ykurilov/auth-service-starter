-- Аварийный отзыв скомпрометированного ключа подписи. При компрометации
-- приватного ключа штатной ротации мало: прежний ключ остаётся в наборе
-- верификации, пока живы выпущенные им токены. revoked_at помечает ключ
-- отозванным — сервис выкидывает его из набора верификации на старте,
-- обесценивая все токены, подписанные им, немедленно.
alter table signing_keys add column revoked_at timestamptz;
