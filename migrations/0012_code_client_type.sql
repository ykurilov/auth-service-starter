-- Тип клиента, по правилам которого вход решал, нужно ли согласие (internal —
-- без экрана согласия). Обмен кода отклоняет код, если тип клиента с тех пор
-- изменился: код, выданный без согласия, не становится кодом external-клиента.
--
-- Значение по умолчанию 'internal' — для копии прежней версии, которая ещё
-- работает во время раскатки и пишет коды без этого поля. Обход согласия оно
-- не открывает: код с типом internal обмен примет, только если клиент сейчас
-- internal, а такому клиенту согласие не нужно. Код external-клиента с этим
-- значением обмен отклонит, и пользователь просто войдёт ещё раз.
alter table authorization_codes add column client_type text not null default 'internal';
-- Коды, выданные до обновления (живут минуту), получают текущий тип клиента.
update authorization_codes
   set client_type = clients.type
  from clients
 where clients.id = authorization_codes.client_id;
